"""Run PREREG.md and write results/RESULTS.md plus an intraday-path chart.

    uv run fx-fix-flows [--data-root /path/Data] [--out results]
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from .core import (  # noqa: E402
    DATA_ROOT,
    ET,
    STRATS,
    USD_SIGN,
    day_table,
    holm,
    load_m1,
    price_grid,
    strategy_net,
    summarize,
)

SYMBOLS = ("USDJPY", "AUDUSD")
START, END = date(2020, 1, 2), date(2026, 9, 30)
BASE, COSTS = 0.5, (0.0, 0.3, 0.5, 1.0)
LEGS = ("preT", "postT", "preE", "postL", "br_local", "br_us")


def _f(v) -> str:
    if isinstance(v, float | np.floating):
        return "—" if np.isnan(v) else f"{v:.3f}" if abs(v) < 10 else f"{v:.1f}"
    return str(v)


def _md(df: pd.DataFrame, name: str) -> str:
    cols = list(df.columns)
    out = [f"| {name} | " + " | ".join(map(str, cols)) + " |", "|" + "---|" * (len(cols) + 1)]
    out += ["| " + " | ".join([str(i)] + [_f(v) for v in r]) + " |" for i, r in df.iterrows()]
    return "\n".join(out)


def usd_path(grid: pd.Series, symbol: str) -> pd.Series:
    """Mean cumulative USD return (bp) by minute of the FX day starting 17:00 ET."""
    s = grid.dropna()
    local = s.index.tz_convert(ET)
    start = (local - pd.Timedelta(hours=17)).normalize()
    minute = ((local - pd.Timedelta(hours=17)) - start) // pd.Timedelta(minutes=1)
    df = pd.DataFrame({"day": start, "m": minute, "p": s.to_numpy()})
    df = df[pd.Index(df.day).dayofweek < 5]
    first = df.groupby("day").p.transform("first")
    df["r"] = USD_SIGN[symbol] * (df.p / first - 1) * 1e4
    return df.groupby("m").r.mean()


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(DATA_ROOT))
    ap.add_argument("--out", default="results")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    md = ["# FX fix flows — results", "",
          "Generated by `uv run fx-fix-flows`; rules in [PREREG.md](../PREREG.md). "
          "Daily returns in bp of price; positive = the rule made money.", ""]
    grids, tbls = {}, {}
    for s in SYMBOLS:
        grids[s] = price_grid(load_m1(s, Path(a.data_root)))
        tbls[s] = day_table(grids[s], s, START, END)
        tbls[s].to_csv(out / f"days_{s}.csv")

    # Gross leg means (USD-position sign already applied: positive = paper direction).
    gl = {f"{s} {leg}": summarize(tbls[s][leg]) for s in SYMBOLS for leg in LEGS}
    gdf = pd.DataFrame(gl).T[["N", "mean_bp", "t", "W"]]
    md += ["## Gross leg returns in the paper's direction (no cost)", "",
           "Positive mean = the leg moved the way the paper says.", "",
           _md(gdf, "pair leg"), ""]

    res, pvals = {}, {}
    for s in SYMBOLS:
        for st in STRATS:
            for c in COSTS:
                res[(s, st, c)] = summarize(strategy_net(tbls[s], s, st, c))
            pvals[f"{st}-{s}"] = res[(s, st, BASE)]["p"]
    base = pd.DataFrame({f"{st}-{s}": res[(s, st, BASE)] for s in SYMBOLS for st in STRATS}).T
    md += [f"## Strategies net of {BASE} pip per leg", "",
           _md(base[["N", "mean_bp", "t", "W", "PF", "ann_bp", "sharpe"]], "rule"), ""]
    sens = pd.DataFrame({f"{st}-{s}": {f"{c} pip": res[(s, st, c)]["mean_bp"] for c in COSTS}
                         for s in SYMBOLS for st in STRATS}).T
    md += ["### Net mean bp/day by cost per leg", "", _md(sens, "rule"), ""]

    for s in SYMBOLS:
        for st in ("T", "BR"):
            x = strategy_net(tbls[s], s, st, BASE)
            yr = x.groupby([d.year for d in x.index]).apply(lambda v: pd.Series(summarize(v)))
            md += [f"### {st}-{s} by year (net {BASE} pip)", "",
                   _md(yr.unstack()[["N", "mean_bp", "t", "W"]], "year"), ""]

    prim = holm({k: pvals[k] for k in ("T-USDJPY", "T-AUDUSD")})
    sec_keys = [f"{st}-{s}" for st in ("E", "W", "BR") for s in SYMBOLS]
    sec = holm({k: pvals[k] for k in sec_keys})
    ok_cost = {k: res[(k.split("-")[1], "T", 1.0)]["mean_bp"] > 0 for k in prim}
    if any(prim[k] and ok_cost[k] for k in prim):
        verdict = "PASS"
    elif any(sec.values()):
        verdict = "SECONDARY ONLY"
    else:
        verdict = "KILL"
    md += ["## Pre-registered verdict", "", f"**{verdict}**", "", "```",
           "primary p: " + ", ".join(f"{k}={pvals[k]:.4f}" for k in prim),
           f"primary Holm reject: {prim}", f"T net > 0 at 1.0 pip: {ok_cost}",
           "secondary p: " + ", ".join(f"{k}={pvals[k]:.4f}" for k in sec_keys),
           f"secondary Holm reject: {sec}", "```", ""]

    fig, axes = plt.subplots(len(SYMBOLS), 1, figsize=(11, 7), sharex=True)
    for ax, s in zip(axes, SYMBOLS, strict=True):
        p = usd_path(grids[s], s)
        ax.plot(p.index / 60, p.to_numpy(), color="#2c3e50")
        ax.axhline(0, lw=0.5, color="k")
        ax.set_ylabel("USD cum. bp")
        ax.set_title(f"{s}: mean USD return through the FX day, 2020–2026 (0 h = 17:00 ET)")
        ax.grid(alpha=0.3)
    axes[-1].set_xlabel("hours after 17:00 ET (Tokyo fix ≈ 3–4 h, ECB ≈ 15.25 h, London ≈ 18 h)")
    fig.tight_layout()
    fig.savefig(out / "usd_path.png", dpi=110)
    plt.close(fig)
    md += ["![usd_path.png](usd_path.png)", ""]

    (out / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
