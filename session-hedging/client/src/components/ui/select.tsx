import * as React from "react";
import { faCheck, faChevronDown } from "@fortawesome/free-solid-svg-icons";
import * as SelectPrimitive from "@radix-ui/react-select";
import { Icon } from "@/lib/icon";
import { cn } from "@/lib/utils";

export const Select = SelectPrimitive.Root;
export const SelectValue = SelectPrimitive.Value;

export const SelectTrigger = React.forwardRef<
  React.ElementRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn(
      "flex h-8 w-full cursor-pointer items-center justify-between gap-2 rounded-none border border-input bg-background px-3 py-2 text-xs focus:outline-none focus:ring-2 focus:ring-ring disabled:cursor-not-allowed disabled:opacity-50",
      className,
    )}
    {...props}
  >
    {children}
    <SelectPrimitive.Icon asChild>
      <span className="inline-flex opacity-50">
        <Icon icon={faChevronDown} className="h-3 w-3" />
      </span>
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
));
SelectTrigger.displayName = "SelectTrigger";

