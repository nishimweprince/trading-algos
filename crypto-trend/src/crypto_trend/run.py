"""Run PREREG.md and write results/RESULTS.md plus an equity chart.

    uv run crypto-trend [--data-root DIR] [--out results]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from .core import load_panel, monthly_universe, portfolio, stats, weights  # noqa: E402
from .fetch import DEFAULT_OUT  # noqa: E402

PERIODS = {"replication": ("2019-01-01", "2025-03-14"), "oos": ("2025-03-15", "2026-10-31")}
COSTS = (0.0005, 0.0010, 0.0025)
BASE = 0.0010


def _f(v) -> str:
    if isinstance(v, float | np.floating):
        return "—" if np.isnan(v) else f"{v:.3f}"
    return str(v)


def _md(df: pd.DataFrame, name: str) -> str:
    cols = list(df.columns)
    out = [f"| {name} | " + " | ".join(map(str, cols)) + " |", "|" + "---|" * (len(cols) + 1)]
    out += ["| " + " | ".join([str(i)] + [_f(v) for v in r]) + " |" for i, r in df.iterrows()]
    return "\n".join(out)


def _slice(s: pd.Series, period: str) -> pd.Series:
    a, b = PERIODS[period]
    return s.loc[a:b]


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(DEFAULT_OUT))
    ap.add_argument("--out", default="results")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    close, qvol = load_panel(Path(a.data_root))
    member = monthly_universe(close, qvol)
    w = weights(close, member)
    btc_ret = close["BTCUSDT"].pct_change()
    btc_member = pd.DataFrame(True, index=close.index, columns=["BTCUSDT"])
    w_btc = weights(close[["BTCUSDT"]], btc_member, n_slots_coins=1)

    runs = {f"rotation @{c:.2%}": portfolio(close, w, c) for c in COSTS}
    runs["BTC-only ensemble @0.10%"] = portfolio(close[["BTCUSDT"]], w_btc, BASE)
    btc_bh = pd.DataFrame({"net": btc_ret})

    md = ["# Crypto trend rotation — results", "",
          "Generated by `uv run crypto-trend`; rules in [PREREG.md](../PREREG.md).", "",
          f"Panel: {close.shape[1]} USDT pairs, {close.index[0]:%Y-%m-%d} → "
          f"{close.index[-1]:%Y-%m-%d}; {int(member.any().sum())} coins ever in the universe; "
          f"average members per day {member.sum(axis=1).loc['2019':].mean():.1f}.", ""]
    for period in PERIODS:
        rows = {k: stats(_slice(v.net, period), _slice(btc_ret, period)) for k, v in runs.items()}
        rows["BTC buy-and-hold"] = stats(_slice(btc_bh.net, period), _slice(btc_ret, period))
        df = pd.DataFrame(rows).T
        a0, b0 = PERIODS[period]
        md += [f"## {period} ({a0} → {b0})", "", _md(df, "strategy (net)"), ""]
        base = runs["rotation @0.10%"].loc[a0:b0]
        md += [f"Rotation @0.10 %: mean gross exposure {base.exposure.mean():.2f}, "
               f"turnover {base.turnover.mean() * 365:.1f}× a year, "
               f"annual cost drag {base.turnover.mean() * 365 * BASE:.2%}.", ""]

    r = runs["rotation @0.10%"].net
    yr = r.loc["2019":].groupby(r.loc["2019":].index.year).apply(
        lambda x: pd.Series(stats(x, btc_ret.reindex(x.index)))).unstack()
    md += ["## Rotation @0.10 % by year", "",
           _md(yr[["CAGR", "sharpe", "maxDD", "alpha_ann", "beta"]], "year"), ""]

    rep = stats(_slice(r, "replication"), _slice(btc_ret, "replication"))
    oos = stats(_slice(r, "oos"), _slice(btc_ret, "oos"))
    reproduces = rep["sharpe"] >= 1.0
    oos_ok = oos["sharpe"] > 0 and oos["alpha_ann"] > 0
    verdict = "KILL" if not reproduces else "PASS" if oos_ok else "HOLD"
    md += ["## Pre-registered verdict", "", f"**{verdict}**", "", "```",
           f"replication Sharpe {rep['sharpe']:.3f} (needs >= 1.0): {reproduces}",
           f"OOS Sharpe {oos['sharpe']:.3f} (> 0) and alpha {oos['alpha_ann']:.3f} "
           f"(t {oos['alpha_t']:.2f}, > 0): {oos_ok}", "```", ""]

    fig, ax = plt.subplots(figsize=(11, 4.5))
    for k, col in (("rotation @0.10%", "#c0392b"), ("BTC-only ensemble @0.10%", "#2980b9")):
        e = (1 + runs[k].net.loc["2019":]).cumprod()
        ax.plot(e.index, e.to_numpy(), label=k, color=col)
    e = (1 + btc_ret.loc["2019":].fillna(0)).cumprod()
    ax.plot(e.index, e.to_numpy(), label="BTC buy-and-hold", color="#7f8c8d", lw=0.8)
    ax.axvline(pd.Timestamp(PERIODS["oos"][0]), ls=":", color="k")
    ax.set_yscale("log")
    ax.set_title("Growth of 1 (log), net of 0.10 % costs; dotted line = start of out-of-sample")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out / "equity.png", dpi=110)
    plt.close(fig)
    md += ["![equity.png](equity.png)", ""]

    w.loc["2019":].round(5).to_csv(out / "weights.csv.gz")
    (out / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
