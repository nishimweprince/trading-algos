"""Run PREREG.md and write results/RESULTS.md.

    uv run crypto-intraday [--data-root DIR] [--out results]
"""

from __future__ import annotations

import argparse
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from .core import day_table, holm, hourly_means, load_5m, summarize
from .fetch import DEFAULT_OUT, SYMBOLS

START, END = date(2022, 1, 1), date(2026, 10, 31)
TAKER, MAKER = 10.0, 4.0
SHORT = {"BTCUSDT": "BTC", "ETHUSDT": "ETH"}


def _f(v) -> str:
    if isinstance(v, float | np.floating):
        return "—" if np.isnan(v) else f"{v:.3f}" if abs(v) < 10 else f"{v:.1f}"
    return str(v)


def _md(df: pd.DataFrame, name: str) -> str:
    cols = list(df.columns)
    out = [f"| {name} | " + " | ".join(map(str, cols)) + " |", "|" + "---|" * (len(cols) + 1)]
    out += ["| " + " | ".join([str(i)] + [_f(v) for v in r]) + " |" for i, r in df.iterrows()]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(DEFAULT_OUT))
    ap.add_argument("--out", default="results")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    tbl, hours = {}, {}
    md = ["# Crypto intraday — results", "",
          "Generated by `uv run crypto-intraday`; rules in [PREREG.md](../PREREG.md). "
          "bp of entry price per trade.", ""]
    for sym in SYMBOLS:
        bars = load_5m(sym, Path(a.data_root))
        px = bars.open
        md.append(f"{sym}: {len(bars):,} 5m bars, {bars.index[0]} → {bars.index[-1]}.")
        tbl[sym] = day_table(px, START, END)
        tbl[sym].to_csv(out / f"days_{sym}.csv")
        hours[sym] = hourly_means(px)
    md.append("")

    rows = {}
    for sym in SYMBOLS:
        s = SHORT[sym]
        for rule in ("r1", "r2", "r2et", "etf_pre", "etf_post"):
            for cost in (0.0, MAKER, TAKER):
                if rule.startswith("etf") and cost:
                    continue  # description only, gross
                rows[f"{rule.upper()} {s} @{cost:g}bp"] = summarize(tbl[sym][rule], cost)
    df = pd.DataFrame(rows).T[["N", "mean_bp", "t", "W", "PF", "total_bp"]]
    md += ["## All rules", "", _md(df, "rule @ cost"), ""]

    for sym in SYMBOLS:
        for rule in ("r1", "r2"):
            x = tbl[sym][rule]
            yr = x.groupby([d.year for d in x.index]).apply(
                lambda v: pd.Series(summarize(v, TAKER))).unstack()
            md += [f"### {rule.upper()} {SHORT[sym]} by year (net {TAKER:g} bp)", "",
                   _md(yr[["N", "mean_bp", "t", "W"]], "year"), ""]

    p = {k: rows[k]["p"] for k in ("R1 BTC @10bp", "R1 ETH @10bp", "R1 BTC @4bp",
                                   "R2 BTC @10bp", "R2 ETH @10bp")}
    primary = p["R1 BTC @10bp"] < 0.05 and rows["R1 BTC @10bp"]["mean_bp"] > 0
    sec = holm({k: v for k, v in p.items() if k != "R1 BTC @10bp"})
    verdict = "PASS" if primary else "SECONDARY ONLY" if any(sec.values()) else "KILL"
    md += ["## Pre-registered verdict", "", f"**{verdict}**", "", "```",
           "p: " + ", ".join(f"{k}={v:.4f}" for k, v in p.items()),
           f"primary pass: {primary}", f"secondary Holm reject: {sec}", "```", ""]

    for sym in SYMBOLS:
        md += [f"## {SHORT[sym]} mean return by UTC hour (gross bp; description only)", "",
               _md(hours[sym], "UTC hour"), ""]

    (out / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
