"""Run the PREREG.md kill test and write results/RESULTS.md.

    uv run fuzzy-osc [--data-root /path/to/Data] [--out results]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from .core import COST, DATA_ROOT, backtest, load_m1, resample, signal, summary

SYMBOLS = ("AUDUSD", "USDJPY", "XAUUSD")
TFS = {"H1": "1h", "M15": "15min"}
HOLDS = (4, 12, 24)


def _f(v) -> str:
    if isinstance(v, float | np.floating):
        return "—" if np.isnan(v) else f"{v:.2f}"
    return str(v)


def _md(df: pd.DataFrame, name: str) -> str:
    cols = list(df.columns)
    out = [f"| {name} | " + " | ".join(map(str, cols)) + " |", "|" + "---|" * (len(cols) + 1)]
    out += ["| " + " | ".join([str(i)] + [_f(v) for v in r]) + " |" for i, r in df.iterrows()]
    return "\n".join(out)


def run_grid(bars_by: dict[str, dict[str, pd.DataFrame]]) -> pd.DataFrame:
    rows, trades = [], {}
    for tf in TFS:
        for variant in ("fuzzy", "crisp"):
            sigs = {s: signal(bars_by[tf][s], variant) for s in SYMBOLS}
            for hold in HOLDS:
                for sign, sname in ((1, "paper"), (-1, "reversed")):
                    pooled = []
                    for s in SYMBOLS:
                        t = backtest(bars_by[tf][s], sigs[s], hold, COST[s], sign)
                        trades[(tf, variant, hold, sname, s)] = t
                        pooled.append(t.net_bps)
                        rows.append({"tf": tf, "variant": variant, "hold": hold, "sign": sname,
                                     "symbol": s, **summary(t.net_bps)})
                    rows.append({"tf": tf, "variant": variant, "hold": hold, "sign": sname,
                                 "symbol": "POOLED", **summary(pd.concat(pooled))})
    return pd.DataFrame(rows), trades


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(DATA_ROOT))
    ap.add_argument("--out", default="results")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    root = Path(a.data_root)

    m1 = {s: load_m1(s, root) for s in SYMBOLS}
    bars_by = {tf: {s: resample(m1[s], r) for s in SYMBOLS} for tf, r in TFS.items()}
    grid, trades = run_grid(bars_by)
    grid.to_csv(out / "grid.csv", index=False)

    prim = grid[(grid.tf == "H1") & (grid.variant == "fuzzy") & (grid.hold == 12)
                & (grid.sign == "paper")].set_index("symbol")
    pooled = prim.loc["POOLED"]
    pos = int((prim.drop("POOLED").mean_bps > 0).sum())
    verdict = "PASS" if (pooled.mean_bps > 0 and pooled.t >= 2 and pos >= 2) else "KILL"

    md = ["# Fuzzy oscillator vote — kill test results", "",
          "Generated by `uv run fuzzy-osc`; rules in [PREREG.md](../PREREG.md). Net of costs, "
          "bps of entry price per trade.", ""]
    md += ["Bars: " + ", ".join(f"{s} {len(m1[s]):,} M1 ({m1[s].index[0]:%Y-%m} → "
                                 f"{m1[s].index[-1]:%Y-%m})" for s in SYMBOLS), ""]
    md += ["## Primary (H1, hold 12, fuzzy, paper sign)", "",
           _md(prim[["N", "mean_bps", "t", "W", "PF", "total_bps"]], "symbol"), "",
           f"Instruments with net mean > 0: {pos}/3.", "", f"**Verdict: {verdict}**", ""]

    t = pd.concat([trades[("H1", "fuzzy", 12, "paper", s)].assign(symbol=s) for s in SYMBOLS])
    yr = t.groupby(t.entry_time.dt.year).net_bps.apply(lambda x: pd.Series(summary(x))).unstack()
    md += ["### Primary pooled by year", "",
           _md(yr[["N", "mean_bps", "t", "W", "PF"]], "year"), ""]
    lng = t.groupby("dir").net_bps.apply(lambda x: pd.Series(summary(x))).unstack()
    md += ["### Primary pooled by direction", "", _md(lng[["N", "mean_bps", "t", "W"]], "dir"), ""]

    pg = grid[grid.symbol == "POOLED"].set_index(["tf", "variant", "hold", "sign"])
    pg.index = [" / ".join(map(str, i)) for i in pg.index]
    md += ["## All pooled variants (description only)", "",
           _md(pg[["N", "mean_bps", "t", "W", "PF"]], "tf / variant / hold / sign"), ""]

    # XAUUSD 2009-2019: extra period, primary rules, not a gate.
    g = resample(load_m1("XAUUSD", root, (2009, 2019)), "1h")
    tx = backtest(g, signal(g, "fuzzy"), 12, COST["XAUUSD"])
    md += ["## XAUUSD 2009–2019, primary rules (not a gate)", "",
           _md(pd.DataFrame([summary(tx.net_bps)], index=["XAUUSD"])
               [["N", "mean_bps", "t", "W", "PF", "total_bps"]], "symbol"), ""]
    (out / "RESULTS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
